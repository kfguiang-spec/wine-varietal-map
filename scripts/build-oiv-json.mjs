const payload = {
  source: SOURCE,
  extracted_at: new Date().toISOString(),
  varieties: Object.values(varieties).map((v) => {
    const entries = Object.entries(v.countries)
      .map(([country, ha]) => ({ country, ha }))
      .sort((a, b) => b.ha - a.ha)
    const reported = entries.reduce((s, e) => s + e.ha, 0)
    return {
      id: v.id,
      name: v.name,
      color: v.color,
      wine: v.wine,
      unit: 'ha',
      year: 2015,
      world_total_ha: v.world_total,
      reported_sum_ha: reported,
      countries: entries,
    }
  }),
}

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, JSON.stringify(payload, null, 2) + '\n')
console.log('Wrote', out, 'varieties:', payload.varieties.length)
for (const v of payload.varieties) {
  console.log(`  ${v.name}: world ${v.world_total_ha} ha, top ${v.countries[0]?.country}`)
}
